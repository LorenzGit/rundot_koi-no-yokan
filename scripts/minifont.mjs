export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Width in pixels that `text` will occupy at the given scale. */
export function textWidth(text, scale = 2) {
    return text.length * (GLYPH_W + 1) * scale;
}

/**
 * Draw uppercase text into an RGBA image. Unknown characters render as blanks
 * rather than throwing — a diagram with a missing glyph is still useful.
 */
export function drawText(img, text, x, y, colour = [20, 20, 20], scale = 2) {
    let cursor = x;
    for (const raw of text) {
        const glyph = GLYPHS[raw] ?? GLYPHS[raw.toUpperCase()] ?? GLYPHS[" "];
        for (let gy = 0; gy < GLYPH_H; gy++) {
            for (let gx = 0; gx < GLYPH_W; gx++) {
                if (glyph[gy][gx] !== "1") continue;
                for (let sy = 0; sy < scale; sy++) {
                    for (let sx = 0; sx < scale; sx++) {
                        const px = cursor + gx * scale + sx;
                        const py = y + gy * scale + sy;
                        if (px < 0 || py < 0 || px >= img.w || py >= img.h) continue;
                        const i = (py * img.w + px) * 4;
                        img.data[i] = colour[0];
                        img.data[i + 1] = colour[1];
                        img.data[i + 2] = colour[2];
                        img.data[i + 3] = 255;
                    }
                }
            }
        }
        cursor += (GLYPH_W + 1) * scale;
    }
    return cursor;
}
